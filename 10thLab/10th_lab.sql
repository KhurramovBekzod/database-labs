DROP DATABASE IF EXISTS coffee WITH (FORCE);
CREATE DATABASE coffee;




CREATE TABLE suppliers (
    sup_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sup_name VARCHAR(255),
    street   VARCHAR(255),
    city     VARCHAR(255),
    state    VARCHAR(255),
    zip      VARCHAR(255)
);

CREATE TABLE coffees (
    cof_name VARCHAR(32),
    sup_id   INTEGER REFERENCES suppliers(sup_id),
    price    REAL,
    sales    INTEGER,
    total    INTEGER,
    PRIMARY KEY (cof_name, sup_id)
);

CREATE TABLE cof_inventory (
    warehouse_id INTEGER,
    cof_name     VARCHAR(32),
    sup_id       INTEGER REFERENCES suppliers(sup_id),
    quan         INTEGER,
    date_val     DATE,
    PRIMARY KEY (warehouse_id, cof_name, sup_id)
);

CREATE TABLE merch_inventory (
    item_id   INTEGER PRIMARY KEY,
    item_name VARCHAR(255),
    sup_id    INTEGER REFERENCES suppliers(sup_id),
    quan      INTEGER,
    date      DATE
);

CREATE TABLE coffee_houses (
    store_id INTEGER PRIMARY KEY,
    city     VARCHAR(255),
    coffee   INTEGER,
    merch    INTEGER,
    total    INTEGER
);



